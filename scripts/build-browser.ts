import { buildBrowserAssetsFromSource } from "../src/BrowserAssets.ts";
import { buildOverlayFromSource } from "../src/vite/overlayAsset.ts";

/**
 * Freeze the browser assets (in-iframe SDK, chrome controller, chrome
 * stylesheet) into `src/generated/browserAssets.ts` (ADR 0007), and the
 * `intervu/vite` plugin's in-page overlay into `src/generated/overlayAsset.ts`,
 * a module of its own so the plugin bundle carries only the overlay. `scripts/build.ts`
 * runs this first so the baked strings are bundled into the single-file binary,
 * which has no source tree to rebuild from. Running from source, the daemon
 * rebuilds these on start instead, so this only needs re-running before a ship
 * build or to refresh the committed baked copy.
 */

const generatedPath = `${import.meta.dir}/../src/generated/browserAssets.ts`;

/** A generated module exporting each baked string under its own name. */
const generatedModule = (exports: Readonly<Record<string, string>>): string =>
  `// @generated by scripts/build-browser.ts - do not edit by hand.
// Regenerate with \`bun run build:browser\`.
${Object.entries(exports)
  .map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};\n`)
  .join("")}`;

const result = await buildBrowserAssetsFromSource();
if (!result.ok) {
  console.error(`build-browser failed: ${result.reason}`);
  process.exit(1);
}

const { sdkJs, chromeJs, chromeCss } = result.bundle;
await Bun.write(
  generatedPath,
  generatedModule({
    bakedSdkJs: sdkJs,
    bakedChromeJs: chromeJs,
    bakedChromeCss: chromeCss,
  }),
);
console.error(`built browser assets -> ${generatedPath}`);

const overlayPath = `${import.meta.dir}/../src/generated/overlayAsset.ts`;

const overlay = await buildOverlayFromSource();
if (!overlay.ok) {
  console.error(`build-browser failed: ${overlay.reason}`);
  process.exit(1);
}

await Bun.write(overlayPath, generatedModule({ bakedOverlayJs: overlay.code }));
console.error(`built in-page overlay -> ${overlayPath}`);

const vitePluginPath = `${import.meta.dir}/../src/generated/vitePluginAsset.ts`;

// The `intervu/vite` plugin as one dependency-free ESM file, the exact bundle
// `scripts/build.ts` publishes as `dist/vite.js`, baked so `intervu setup
// vite` can write it into a project with no package manager and no network.
// Built after the overlay above, so the bundle inlines the fresh baked copy.
const vitePluginResult = await Bun.build({
  entrypoints: [`${import.meta.dir}/../src/vite/plugin.ts`],
  target: "node",
  format: "esm",
});
const vitePluginArtifact = vitePluginResult.success
  ? vitePluginResult.outputs[0]
  : undefined;
if (vitePluginArtifact === undefined) {
  for (const message of vitePluginResult.logs) {
    console.error(message);
  }
  console.error("build produced no vite plugin output");
  process.exit(1);
}
await Bun.write(
  vitePluginPath,
  generatedModule({ bakedVitePluginJs: await vitePluginArtifact.text() }),
);
console.error(`built vite plugin asset -> ${vitePluginPath}`);
